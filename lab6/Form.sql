DROP TABLE IF EXISTS posts CASCADE;
DROP TABLE IF EXISTS topics CASCADE;
DROP SEQUENCE IF EXISTS posts_id_seq;

CREATE TABLE topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    author VARCHAR(50) NOT NULL,
    category VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_topics_title UNIQUE (title),
    CONSTRAINT ck_topics_category CHECK (category IN ('STUDY', 'GAMES', 'OTHER'))
);

CREATE SEQUENCE posts_id_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE posts (
    id BIGINT PRIMARY KEY DEFAULT nextval('posts_id_seq'),
    topic_id BIGINT NOT NULL,
    content VARCHAR(2000) NOT NULL,
    author VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_posts_topic FOREIGN KEY (topic_id) REFERENCES topics(id)
);

ALTER SEQUENCE posts_id_seq OWNED BY posts.id;

CREATE INDEX idx_posts_topic_id ON posts(topic_id);

